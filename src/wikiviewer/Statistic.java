package wikiviewer;

/**
 * Η διεπαφή Statistic ορίζει τη βασική δομή για την αναπαράσταση στατιστικών δεδομένων.
 * Χρησιμοποιείται για την ομοιόμορφη διαχείριση μετρήσιμων στοιχείων στην εφαρμογή, 
 * όπως ο αριθμός άρθρων ανά κατηγορία ή η συχνότητα εμφάνισης λέξεων-κλειδιών.
 * * <p>Κλάσεις που υλοποιούν αυτό το interface (π.χ. CategoryStat, KeywordStat) μπορούν 
 * να χρησιμοποιηθούν πολυμορφικά σε πίνακες και γραφήματα.</p>
 * @author PLH24Team Vasiliadou - Aggelopoulos - Kosmidis
 */
public interface Statistic
{
    /**
     * Επιστρέφει το όνομα του στοιχείου που αφορά το στατιστικό.
     * @return Μια συμβολοσειρά (String) που αντιπροσωπεύει το όνομα 
     * (π.χ. το όνομα μιας κατηγορίας ή μια λέξη-κλειδί).
     */
    public String getName();
    
    /**
     * Επιστρέφει το πλήθος ή τη συχνότητα εμφάνισης του συγκεκριμένου στοιχείου.
     * @return Ένας ακέραιος (int) που αντιπροσωπεύει την καταμέτρηση (count).
     */
    public int getCount(); 
    
}
